describe('Deleting expenses', () => {
  it('deletes one expense and updates the count and total', () => {
    cy.visit('/')
    cy.get('[data-cy="title"]').type('Lunch')
    cy.get('[data-cy="amount"]').type('250')
    cy.get('[data-cy="add-expense"]').click()
    cy.get('[data-cy="title"]').type('Cab')
    cy.get('[data-cy="amount"]').type('400')
    cy.get('[data-cy="category"]').select('Travel')
    cy.get('[data-cy="add-expense"]').click()
    cy.get('[data-cy="expense-item"]').should('have.length', 2)
    cy.get('[data-cy="expense-item"]').contains('Lunch').closest('[data-cy="expense-item"]').find('[data-cy="delete-expense"]').click()
    cy.get('[data-cy="expense-item"]').should('have.length', 1).and('contain', 'Cab').and('not.contain', 'Lunch')
    cy.get('[data-cy="count"]').should('contain', '1 expense shown')
    cy.get('[data-cy="total"]').should('contain', '400.00')
    cy.get('[data-cy="delete-expense"]').click()
    cy.get('[data-cy="expense-item"]').should('not.exist')
    cy.get('[data-cy="count"]').should('contain', '0 expenses shown')
    cy.get('[data-cy="total"]').should('contain', '0.00')
  })
})
